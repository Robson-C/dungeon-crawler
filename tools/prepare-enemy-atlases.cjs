const fs = require("node:fs");
const path = require("node:path");
const sharp = require(require.resolve("sharp", {paths:[path.dirname(process.execPath)]}));
const root = path.resolve(__dirname,"..");
const families = [
  ["skeleton","esqueleto-sem-cabeca","Esqueleto sem cabeça",21,"swipe"],
  ["slime","gosma","Gosma",11,"body"],
  ["rat","rato","Rato",12,"bite"],
  ["beetle","carapaca","Carapaça",13,"ram"],
  ["armor","armadura-possuida","Armadura possuída",24,"mace"]
];

async function main() {
  const definitions = {};
  for (const [id,sourceId,name,height,attack] of families) {
    const input=path.join(root,"assets/enemies/sources",sourceId+".png");
    const {width,height:sourceHeight}=await sharp(input).metadata();
    const parts=[];
    for(let row=0;row<5;row++) for(let column=0;column<8;column++) {
      const x=Math.round(column*width/8),y=Math.round(row*sourceHeight/5);
      const crop={left:x,top:y,width:Math.round((column+1)*width/8)-x,height:Math.round((row+1)*sourceHeight/5)-y};
      const sprite=await sharp(input).extract(crop).resize(192,192,{fit:"contain",background:{r:0,g:0,b:0,alpha:0}}).png().toBuffer();
      parts.push({input:sprite,left:column*192,top:row*192});
    }
    const atlas=await sharp({create:{width:1536,height:960,channels:4,background:{r:0,g:0,b:0,alpha:0}}})
      .composite(parts).webp({lossless:true}).toBuffer();
    fs.writeFileSync(path.join(root,"assets/enemies",id+".webp"),atlas);
    const {data,info}=await sharp(atlas).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const frames=[];
    for(let row=0;row<5;row++) for(let column=0;column<8;column++) {
      let left=192,right=0,top=192,bottom=0,count=0;
      for(let y=0;y<192;y++)for(let x=0;x<192;x++) {
        if(data[((row*192+y)*info.width+column*192+x)*4+3]>128) {
          count++;left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
        }
      }
      if(count<150)throw Error(`Empty frame ${id} ${row} ${column}`);
      frames.push({x:column*192,y:row*192,w:192,h:192,anchorX:96,ground:bottom+1,
        bounds:{left,top,right,bottom},visiblePixels:count});
    }
    // One common scale per creature preserves squash, stride and raised attacks.
    const idleHeights=[0,8,16,24,32].map(i=>frames[i].ground-frames[i].bounds.top).sort((a,b)=>a-b);
    definitions[id]={name,height,attack,image:`assets/enemies/${id}.webp`,referenceHeight:idleHeights[2],frames};
  }
  fs.writeFileSync(path.join(root,"enemy-art-data.js"),'"use strict";\n// Generated by tools/prepare-enemy-atlases.cjs. Five views × eight whole-body poses.\nconst enemyArtData = '+JSON.stringify(definitions,null,2)+';\n');
  console.log(JSON.stringify({result:"passed",families:Object.keys(definitions),frames:200,atlasSize:[1536,960]}));
}
main().catch(error=>{console.error(error);process.exitCode=1;});
